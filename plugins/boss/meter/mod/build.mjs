// Bundle the one authored meter module (mod/src/register.mjs and the model files in ../) into the
// committed, self-contained hooks module hooks/meter-register.js that hooks.json names under "modules".
// Marketplace installs run no build step, so the bundle is committed and a test checks it is fresh.
//
//   node meter/mod/build.mjs                 write <plugin>/hooks/meter-register.js
//   node meter/mod/build.mjs --out <file>    write somewhere else (used by the staleness test)
//
// esbuild comes from meter/package.json (run `npm ci` in meter/ once).
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const plugin = path.resolve(here, '../..');
const require = createRequire(path.join(here, '../package.json'));
let esbuild;
try { esbuild = require('esbuild'); } catch {
  console.error('esbuild is not installed: run `npm ci` in plugins/boss/meter first.');
  process.exit(2);
}
const args = process.argv.slice(2), at = args.indexOf('--out');
const outfile = at >= 0 && args[at + 1] ? path.resolve(args[at + 1]) : path.join(plugin, 'hooks/meter-register.js');
await esbuild.build({
  absWorkingDir: plugin, // keeps the path comments in the bundle identical on every machine
  entryPoints: ['meter/mod/src/register.mjs'],
  outfile,
  bundle: true, platform: 'neutral', format: 'esm', target: 'es2023', logLevel: 'warning',
  banner: { js: '// Generated by meter/mod/build.mjs from meter/mod/src and meter/*.mjs. Do not edit.' },
});
